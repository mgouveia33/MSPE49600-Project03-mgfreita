# Define norm function and RBF kernel phi
def norm(a,b):
    return np.sqrt(np.dot(a-b,a-b))
def phi(a,b,sigma):
    return np.exp(-norm(a,b)**2/(2*sigma**2))

# Define RBF matrix
def rbf_matrix(A,B,sigma):
    matrix = np.zeros((len(A),len(B)))
    for i in range(len(A)):
        for j in range(len(B)):
            matrix[i, j] = phi(A[i], B[j], sigma)   # Entry (i,j) computes the kernel between row i of A and row j of B
    return matrix

# Define Gram matrix on the normalized X_train
Gram_matrix =  rbf_matrix(X_train_normalized,X_train_normalized,sigma = 0.2)
print("Gram matrix shape \n", Gram_matrix.shape)
print("The diagonal is indeed 1: \n", np.diagonal(Gram_matrix))

# Return coefficient vector of RBF fitting
def fit_rbf(X,y,sigma,lam):
    Gram_matrix = rbf_matrix(X,X,sigma)
    I = np.eye(len(Gram_matrix))
    return np.linalg.solve(Gram_matrix+lam*I,y)

# Return predicted response
def predict_rbf(X_new, centers, b, sigma):
    Gram_matrix = rbf_matrix(X_new, centers, sigma)
    return Gram_matrix @ b   # Vector ouput. Entry i gives the sum of b_j phi(x_i, c_j) for j in centers.

# Fit the vector of coefficients
