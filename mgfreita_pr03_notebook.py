# Return vector of predictions after perfoming LOOCV
def loocv_rbf(X,y,sigma,lam):
  predictions = np.zeros(len(X))
  for i in range(len(X)):
    X_omit  = np.delete(X, i , axis = 0)
    y_omit = np.delete(y, i ,axis = 0)
    b_omit = fit_rbf(X_omit, y_omit, sigma, lam)
    yhat_omit = predict_rbf(X[i:i+1], X_omit, b_omit, sigma)   # Predict the i-th response
    predictions[i] = yhat_omit.item()
  return predictions.reshape(-1,1)

