# Function that construct design matrix of quadractic model
def design(Z):
        z1, z2 = Z[:,0], Z[:,1]
        return np.column_stack((np.ones(len(z1)), z1, z2, z1**2, z2**2, z1*z2))

# Fit quadractic regression and compute predicted response in LOO
def loocv_quad(X,y):
  predictions = np.zeros(len(X))
  for i in range(len(X)):
    X_omit = np.delete(X, i , axis = 0)
    y_omit = np.delete(y, i ,axis = 0)
    design(X_omit)
    b_omit = np.linalg.pinv(design(X_omit))@ y_omit
    yhat_omit = design(X[i:i+1])@ b_omit
    predictions[i]  = yhat_omit.item()
  return predictions.reshape(-1,1)

# Fit and predict lap time with quadratic model
def predict_quad(X,y, X_new):
  b = np.linalg.pinv(design(X))@ y
  return design(X_new)@b

